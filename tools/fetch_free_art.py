def api(params):
    url = API + '?' + urllib.parse.urlencode(dict(params, format='json'))
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.load(r)

def strip_html(s):
    return re.sub(r'<[^>]+>', '', s or '').strip()

def find(query, width):
    data = api({'action': 'query', 'generator': 'search', 'gsrsearch': query, 'gsrnamespace': 6, 'gsrlimit': 12,
                'prop': 'imageinfo', 'iiprop': 'url|extmetadata|mime', 'iiurlwidth': width})
    pages = sorted((data.get('query') or {}).get('pages', {}).values(), key=lambda p: p.get('index', 99))
    for p in pages:
        info = (p.get('imageinfo') or [{}])[0]
        if info.get('mime') not in ('image/jpeg', 'image/png') or re.search(r'logo|icon|title card', p['title'], re.I):
            continue
        meta = info.get('extmetadata') or {}
        licence = strip_html((meta.get('LicenseShortName') or {}).get('value'))
        if not FREE.match(licence):
            continue
        return {'title': p['title'], 'licence': licence, 'author': strip_html((meta.get('Artist') or {}).get('value')) or 'Unknown',
                'source': info.get('descriptionurl'), 'thumb': info.get('thumburl') or info.get('url'), 'mime': info['mime']}
    return None

def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    credits = {}
    for key, (width, queries) in WANTED.items():
        hit = None
        for q in queries:
            try:
                hit = find(q, width)
            except Exception as e:
                print('  ! search failed:', q, e)
            time.sleep(0.3)
            if hit:
                break
        if not hit:
            print('  - %-28s nothing free found; stays generated' % key)
            continue
        ext = '.png' if hit['mime'] == 'image/png' else '.jpg'
        name = re.sub(r'[^A-Za-z0-9_.-]', '_', key) + ext
        req = urllib.request.Request(hit['thumb'], headers={'User-Agent': UA})
        with urllib.request.urlopen(req, timeout=30) as r, open(os.path.join(OUT, name), 'wb') as f:
            f.write(r.read())
        credits[key] = dict(hit, file=name)
        print('  + %-28s %s  [%s]' % (key, hit['title'], hit['licence']))
        time.sleep(0.3)
    json.dump(credits, open(os.path.join(OUT, 'credits.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    write_credits(credits)
    print('%d of %d images found' % (len(credits), len(WANTED)))

def write_credits(credits):
    """docs/screenshots/CREDITS.md: who made each image in the screenshots, and its licence."""
    lines = ['# Screenshot image credits', '',
             'The films, shows and music in the screenshots are real works whose artwork is freely licensed: '
             'Blender Foundation open movies (Creative Commons), public-domain films, TV publicity photographs and portraits. '
             'Every image comes from Wikimedia Commons; follow each link for its full licence. Images not listed here '
             '(library tiles, the profile picture, some stills) are generated by `tests/readme_shots.cpp`.', '',
             '| Image | Author | Licence | Source |', '|---|---|---|---|']
    for key, c in sorted(credits.items()):
        title = c['title'].replace('File:', '').replace('|', '/')
        author = re.sub(r'\s+', ' ', c['author']).replace('|', '/')[:120]
        lines.append('| %s | %s | %s | [%s](%s) |' % (key, author, c['licence'], title, c['source']))
    path = os.path.join(ROOT, 'docs', 'screenshots', 'CREDITS.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
